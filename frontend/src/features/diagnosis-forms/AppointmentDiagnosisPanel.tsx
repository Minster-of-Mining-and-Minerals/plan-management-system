"use client";

import { useEffect, useState } from "react";
import { Stethoscope, Save } from "lucide-react";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import Loading01 from "@/features/template/component/Loading/Loading01";
import { DynamicUserFormFields } from "@/components/dynamic-form/DynamicUserFormFields";
import {
  useGetAppointmentDiagnosisQuery,
  useSaveAppointmentDiagnosisMutation,
} from "@/redux/api/diagnosisRecordApi";
import type { DynamicFormValues } from "@/redux/types/formField";
import { validateDynamicForm } from "@/lib/dynamicFormValidation";
import { flattenFormFields } from "@/redux/types/formField";
import { toast } from "sonner";
import {
  formDataHasPendingCanvasPreviews,
  sanitizeFormDataCanvasFields,
} from "@/components/canvas-annotation/canvasAnnotationUtils";
import { ActiveClinicalResponsibilitiesPanel } from "@/features/orders/components/ActiveClinicalResponsibilitiesPanel";

type Props = {
  appointmentId: string;
};

export function AppointmentDiagnosisPanel({ appointmentId }: Props) {
  const { data, isLoading, isError } = useGetAppointmentDiagnosisQuery(appointmentId);
  const [saveDiagnosis, { isLoading: saving }] = useSaveAppointmentDiagnosisMutation();

  const [values, setValues] = useState<DynamicFormValues>({});
  const [errors, setErrors] = useState<Record<string, string>>({});

  useEffect(() => {
    if (data?.record?.form_data) {
      setValues(data.record.form_data as DynamicFormValues);
    } else if (data?.form) {
      const defaults: DynamicFormValues = {};
      for (const field of data.form.fields || []) {
        if (field.config?.default_value !== undefined) {
          defaults[field.field_key] = field.config.default_value;
        }
      }
      setValues(defaults);
    }
  }, [data]);

  const grouped = data?.form;

  const handleChange = (key: string, value: unknown) => {
    setValues((prev) => ({ ...prev, [key]: value }));
    setErrors((prev) => {
      const next = { ...prev };
      delete next[key];
      return next;
    });
  };

  const handleSave = async (status: "draft" | "submitted") => {
    if (!grouped) return;

    const fields = flattenFormFields(grouped).filter((f) => f.is_visible);
    const fieldErrors =
      status === "draft"
        ? {}
        : validateDynamicForm(
            fields.filter((f) => f.is_required),
            values
          );

    if (Object.keys(fieldErrors).length) {
      setErrors(fieldErrors);
      toast.error("Please fix validation errors before saving");
      return;
    }

    if (grouped && formDataHasPendingCanvasPreviews(values, grouped)) {
      toast.error(
        "Canvas preview is still uploading. Wait a moment, then save again."
      );
      return;
    }

    const form_data = grouped
      ? sanitizeFormDataCanvasFields(values, grouped)
      : values;

    try {
      const res = await saveDiagnosis({
        appointmentId,
        form_data,
        status,
      }).unwrap();

      const autoCount = (res as any)?.autoGeneratedOrders?.length || 0;
      if (autoCount > 0) {
        toast.success(
          `Diagnosis submitted! ${autoCount} Clinical Order${autoCount > 1 ? "s" : ""} auto-placed into department queues.`
        );
      } else {
        toast.success(
          status === "draft" ? "Diagnosis draft saved" : "Diagnosis submitted"
        );
      }
    } catch (e: unknown) {
      const message =
        e && typeof e === "object" && "data" in e
          ? String((e as { data?: { message?: string } }).data?.message)
          : "Failed to save diagnosis";
      toast.error(message);
    }
  };

  const recordStatus = data?.record?.status;

  if (isLoading) return <Loading01 />;

  if (isError || !data) {
    return (
      <Card>
        <CardContent className="py-8 text-center text-muted-foreground">
          Unable to load diagnosis form.
        </CardContent>
      </Card>
    );
  }

  const noStaffConfig = !data.formConfig;
  const hasFields =
    !noStaffConfig && (grouped?.fields || []).some((f) => f.is_visible);

  return (
    <Card>
      <CardHeader className="flex flex-row items-center justify-between gap-3">
        <CardTitle className="flex items-center gap-2 text-base">
          <Stethoscope className="h-4 w-4" />
          Diagnosis
        </CardTitle>
        {recordStatus && (
          <Badge variant="outline">{recordStatus}</Badge>
        )}
      </CardHeader>
      <CardContent className="space-y-6">
        {/* Real-time active clinical orders context */}
        <ActiveClinicalResponsibilitiesPanel appointmentId={appointmentId} />

        {noStaffConfig ? (
          <p className="text-sm text-muted-foreground">
            No diagnosis form is assigned to your staff account yet. An administrator can
            assign a template from Users → Configure Diagnosis Form.
          </p>
        ) : (
          <p className="text-sm text-muted-foreground">
            Form configuration: <strong>{data.formConfig!.title}</strong> (staff-specific)
          </p>
        )}

        {!noStaffConfig && !hasFields ? (
          <p className="text-sm text-muted-foreground">
            Your diagnosis form has no visible fields yet. Ask an administrator to customize
            your staff form.
          </p>
        ) : !noStaffConfig && grouped ? (
          <DynamicUserFormFields
            grouped={grouped}
            values={values}
            errors={errors}
            onChange={handleChange}
          />
        ) : null}

        <div className="flex flex-wrap gap-2 pt-2">
          <Button
            variant="outline"
            disabled={saving || !hasFields || noStaffConfig}
            onClick={() => handleSave("draft")}
          >
            Save draft
          </Button>
          <Button
            disabled={saving || !hasFields || noStaffConfig}
            onClick={() => handleSave("submitted")}
          >
            <Save className="mr-2 h-4 w-4" />
            Submit diagnosis
          </Button>
        </div>
      </CardContent>
    </Card>
  );
}
